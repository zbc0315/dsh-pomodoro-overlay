import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const packageName = '@tom2012/dsh-pomodoro-overlay'
const outputPath = join(root, 'client', 'client.js')

const result = await build({
  entryPoints: [join(root, 'src', 'client.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'chrome110',
  external: ['react'],
  minify: true,
  legalComments: 'none',
})

const bundle = result.outputFiles[0].text
const output = `/* ${packageName} — generated by tools/build.mjs; do not edit directly. */\n` +
  `window.__ModuleLoader__.load({ id: ${JSON.stringify(packageName)}, factory: (require) => {\n` +
  `var module = { exports: {} }; var exports = module.exports;\n` +
  `${bundle}\n` +
  `return module.exports;\n` +
  `} });\n`

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== output) throw new Error('client/client.js is stale; run npm run build')
} else {
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, output)
  console.log(`Built client/client.js (${Buffer.byteLength(output)} bytes)`)
}
